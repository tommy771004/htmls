def ammo(g, H):
    # 彈鏈盒：橄欖硬殼，側面壓筋，頂蓋與前扣；group='mag'
    x0, x1 = BX - .040, BX + .040
    box = H.prism(H.fillet([(x0, -.0950, .004), (x1, -.0950, .004), (x1, .0250, .002), (x0, .0250, .002)], seg=2), .1120, .2000, 'xz', 'box')
    bev(H, box, H.BW_MID, 1)
    cuts = []
    for sx, xe in ((1, x1), (-1, x0)):
        for z in (.0060, -.0060, -.0180):
            cuts.append(H.prism(H.fillet([(.1200, z, .0015), (.1920, z, .0015), (.1920, z + .0060, .0015), (.1200, z + .0060, .0015)], seg=1), xe - sx * .0012, xe + sx * .01, 'yz'))
    H.cut(box, *cuts)
    g.add(trim(H, box), 'olive', None, group='mag')
    lid = H.prism(H.fillet([(x0 - .0015, .0250, .002), (x1 + .0015, .0250, .002), (x1 + .0015, .0340, .002), (x0 - .0015, .0340, .002)], seg=1), .1105, .2015, 'xz', 'lid')
    H.cut(lid, H.box(.0340, .0640, .1040, .1600, .0280, .05))
    g.add(bev(H, lid, H.BW_FINE, 1), 'gripol', None, group='mag')
    # 前扣與提帶
    g.add(H.box(BX - .0100, BX + .0100, .2000, .2045, .0040, .0300, 'clasp'), 'steel', H.BW_FINE, group='mag')
    g.add(H.prism(H.fillet([(.1880, -.0100, .001), (.2030, -.0100, .001), (.2030, .0080, .001), (.1880, .0080, .001)], seg=1), x1, x1 + .0028, 'yz', 'tab'), 'steel', None, group='mag')
    # 外露彈鏈：彈殼軸沿 Y，從盒頂彎進進彈口
    path = [(.0500, .0300), (.0522, .0420), (.0512, .0545), (.0470, .0660), (.0405, .0760), (.0300, .0815)]
    for x, z in path:
        cs = H.lathe([(.1060, 0), (.1060, .0014), (.1064, .0016), (.1064, .0047), (.1076, .0047), (.1082, .0040), (.1096, .0049), (.1490, .0049), (.1530, .0033), (.1580, .0031), (.1630, .0012), (.1640, 0)], 12, (x, z))
        g.add(cs, 'steel', None, group='mag')
    for i, (x, z) in enumerate(path):
        a = path[max(i - 1, 0)]; b = path[min(i + 1, len(path) - 1)]
        th = math.atan2(-(b[0] - a[0]), b[1] - a[1])     # 彈鏈前進方向的法線朝外
        for yc in (.1190, .1420):
            loops = []
            for k in range(7):
                t = th - math.pi * .55 + math.pi * 1.1 * k / 6
                c, n = math.cos(t), math.sin(t)
                loops.append([(x + c * .0050, yc - .0026, z + n * .0050), (x + c * .0050, yc + .0026, z + n * .0050), (x + c * .0060, yc + .0026, z + n * .0060), (x + c * .0060, yc - .0026, z + n * .0060)])
            g.add(H.loft(loops, 'link'), 'oxide', None, group='mag')


def build(H):
    g = H.Gun('n9')
    grip_group(g, H)
    receiver(g, H)
    cover(g, H)
    sights(g, H)
    handguard(g, H)
    barrel_group(g, H)
    stock(g, H)
    ammo(g, H)
    g.marks['muzzle'] = (0, .590, BZ)
    return g
