    prof = H.fillet([(-.1140, .0960, .003), (-.2500, .0900, .006), (-.3300, .0900, .003), (-.3300, -.0280, .004), (-.3120, -.0320, .006), (-.2740, -.0120, .006), (-.2520, .0280, .008), (-.2150, .0330, .010), (-.1140, .0420, .003)], seg=2)
