def bev(H, ob, w, seg=1, ang=30):
    """導角段數自己定。工具的 finish_part 固定三段，零件一多就爆預算。"""
    H.bevel_now(ob, w, seg=seg, angle=math.radians(ang)); return ob


def riv(g, H, x, y, z, r=.0019, h=.0009, axis='x', mat='steel', n=10):
    """省面的鉚釘。工具的 g.pin 一顆 400 面，這裡一顆 30 面。h 帶正負號決定朝向。"""
    ob = H.lathe([(0, r), (h * .6, r * .82), (h, r * .36), (h, 0)], n, (y, z) if axis == 'x' else (x, z), axis, 'rv')
    if axis == 'x': H.move(ob, x)
    else: H.move(ob, 0, y)
    return g.add(ob, mat, None)


def screw(g, H, x, y, z, r=.0028, h=.0009, mat='steel'):
    """一字螺絲：沿 X 的圓頭加一道槽。h 帶正負號決定朝向。"""
    ob = H.lathe([(0, r), (h * .7, r), (h, r * .8), (h, 0)], 12, (y, z), 'x', 'sc'); H.move(ob, x)
