def bev(H, ob, w, seg=2):
    """省面導角：兩段，給大件用。之後 g.add 的 bw 傳 None。"""
    H.bevel_now(ob, w, seg=seg)
    return ob


def trim(H, ob, w=None, seg=1):
    """切完細節後的收邊導角。避開第一次導角的弧面，凸稜留在同一個 UV 島內，磨損線才連續。"""
    H.bevel_now(ob, w or H.BW_FINE * 1.4, seg=seg, angle=math.radians(44))
    return ob


def hexb(g, H, x, y, z, r=.0030, h=.0008, mat='oxide'):
    """低面數內六角螺絲，軸沿 X，h 帶正負號決定朝向。"""
    g.add(H.move(H.lathe([(0, r), (h, r), (h, r * .5), (h * .2, r * .5), (h * .2, 0)], 10, (y, z), 'x'), x), mat, None)


def pin(g, H, x, y, z, r=.0026, h=.0007, axis='x', mat='oxide'):
    """低面數平頭銷。"""
    prof = [(0, r), (h, r), (h, 0)]
    if axis == 'x': o = H.move(H.lathe(prof, 10, (y, z), 'x'), x)
    elif axis == 'y': o = H.move(H.lathe(prof, 10, (x, z), 'y'), 0, y)
    else: o = H.move(H.lathe(prof, 10, (x, y), 'z'), 0, 0, z)
    g.add(o, mat, None)


def comb(g, H, y0, y1, z, hw=.0104, pitch=.01, mat='alum'):
    """低面數短導軌：一條底座加一排無導角的齒。"""
    base = H.prism([(-hw + .0022, z), (hw - .0022, z), (hw - .0022, z + .0032), (-hw + .0022, z + .0032)], y0, y1, 'xz', 'rb')
    g.add(base, mat, None)
    tooth = [(-hw + .0022, z + .0030), (-hw, z + .0040), (-hw + .0030, z + .0050), (hw - .0030, z + .0050), (hw, z + .0040), (hw - .0022, z + .0030)]
    n = int((y1 - y0 - .002) / pitch); y = y0 + ((y1 - y0) - n * pitch + .0052) / 2; teeth = []
    for i in range(n):
        teeth.append(H.prism(tooth, y, y + pitch - .0052, 'xz', 'rt')); y += pitch
    g.add(H._join_mesh(teeth), mat, None)


