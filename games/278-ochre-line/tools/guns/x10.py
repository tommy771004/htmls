def stock(g, H):
    # 固定托：托頂沿機匣頂線微降，下緣斜降；上半一道窄開槽，趾部一個背帶孔
    prof = H.fillet([(-.0900, .1000, .003), (-.3020, .0945, .003), (-.3020, -.0340, .004), (-.2900, -.0395, .006), (-.1500, .0150, .012), (-.1150, .0240, .010), (-.0900, .0320, .004)], seg=2)
    st = H.prism(prof, -.0165, .0165, 'yz', 'stock')
    bev(H, st, H.BW)
    cuts = [H.prism(H.fillet([(-.2500, .0490, .005), (-.1420, .0580, .005), (-.1260, .0770, .004), (-.2500, .0770, .005)], seg=2), -.03, .03, 'yz')]
    cuts.append(H.prism(H.fillet([(-.2760, -.0180, .004), (-.2480, -.0060, .004), (-.2520, .0040, .004), (-.2780, -.0080, .004)], seg=2), -.03, .03, 'yz'))
    for sx in (1, -1):
        # 下半側面淺銑面，順著下緣
        cuts.append(H.prism(H.fillet([(-.2880, .0120, .004), (-.2880, .0360, .004), (-.1420, .0360, .006), (-.1420, .0300, .006), (-.2240, .0020, .004)], seg=2), sx * .0150, sx * .03, 'yz'))
    H.cut(st, *cuts)
    g.add(trim(H, st), 'gripol', None)
    # 頰枕：可拆的黑色片，兩顆固定螺絲
    g.add(H.loft_y([(-.1200, .1035, .0960, .0150, .004, .001), (-.1400, .1058, .0960, .0160, .005, .001), (-.2500, .1040, .0945, .0160, .005, .001), (-.2700, .1012, .0945, .0150, .004, .001)], 2, 'cheek'), 'rubber', None)
