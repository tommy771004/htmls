def bev(H, ob, w, seg=1, ang=30):
    """導角段數自己定。工具的 finish_part 固定三段，零件一多就爆預算。"""
    H.bevel_now(ob, w, seg=seg, angle=math.radians(ang)); return ob


def riv(g, H, x, y, z, r=.0019, h=.0009, axis='x', mat='steel', n=10):
    """省面的銷頭。h 帶正負號決定朝向。"""
    ob = H.lathe([(0, r), (h * .6, r * .82), (h, r * .36), (h, 0)], n, (y, z) if axis == 'x' else ((x, y) if axis == 'z' else (x, z)), axis, 'rv')
    if axis == 'x': H.move(ob, x)
    elif axis == 'z': H.move(ob, 0, 0, z)
    else: H.move(ob, 0, y)
    return g.add(ob, mat, None)


def screw(g, H, x, y, z, r=.0024, h=.0010, axis='x', mat='oxide'):
    """內六角螺絲：外圈加六角凹。h 帶正負號決定朝向。"""
    ob = H.lathe([(0, r), (h, r), (h, r * .5), (h * .3, r * .5), (h * .3, 0)], 12, (y, z) if axis == 'x' else (x, y), axis, 'sc')
    if axis == 'x': H.move(ob, x)
    else: H.move(ob, 0, 0, z)
    return g.add(ob, mat, None)


def pipe(H, path, r, n=10, closed=False, name='pipe'):
    """沿 3D 路徑掃圓管，框架用平行傳送。path=[(x,y,z),...]"""
    from mathutils import Vector
    N = len(path); P = [Vector(p) for p in path]; loops = []; nrm = None
    for i, p in enumerate(P):
        a = P[(i - 1) % N] if closed or i > 0 else p
        b = P[(i + 1) % N] if closed or i < N - 1 else p
        t = (b - a).normalized()
        if nrm is None:
            nrm = t.cross(Vector((1, 0, 0)) if abs(t.x) < .9 else Vector((0, 1, 0))).normalized()
        nrm = (nrm - t * nrm.dot(t)).normalized(); bi = t.cross(nrm)
        loops.append([tuple(p + nrm * (r * math.cos(2 * math.pi * k / n)) + bi * (r * math.sin(2 * math.pi * k / n))) for k in range(n)])
    if closed: loops.append(loops[0])
    return H.loft(loops, name, cap=not closed)


