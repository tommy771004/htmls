"""C7 緊湊手槍：黑色聚合物槍身、圓肩滑套、頂部減重窗、加長彈匣。原創外型，規格見 dist/GUN_SPEC.md。

和 P9（多邊形切角、黑色全身）、R50（大型全尺寸）的差別：
  短而厚的圓肩滑套、前後都是直立勺形刻槽、前段頂部開窗露出槍管、滑套尾端鋼蓋板，
  握把下方接一段帶指溝的加長彈匣套，側面一眼看得出是二十發。
"""
import math

KIND = 'pistol'
POSE = dict(kind='pistol', r=dict(rake=-6, yaw=24, fore=(-0.1, 0.27, 0.95), upper=(0.25, 0.0, 0.97), c=(0.0, -0.03, -0.008), grip=dict(ys=(0.02, -0.005), ys45=(-0.025, -0.045), mcp=-.014, span=.072, back=1.4), trigger=(0.003, 0.007, 0.06), spread=dict(middle=-4, ring=-6, pinky=-9), thumb=dict(out=(0.7, 0.0, -0.7), y=0.017, z=0.022, dir=(0, -0.3, 0.95))))
RELOAD = dict(c=(0.0, -0.09, -0.03), n=(-0.12, 0.97, 0.1), fa=(-0.2, 0.1, 0.97), fore=(-0.35, 0.2, 0.92), upper=(-0.4, -0.3, 0.87), palm=0.02)
ENGRAVE = [(-.0136, -1, .046, .0522, .0032, 'C7 OCHRE LINE'), (.0136, 1, -.018, .0522, .0030, 'NO 70218 CAL 9')]


def build(H):
    g = H.Gun('c7'); BZ = .0680; S0, S1 = -.0560, .1040
    F, P, B, C, L = H.fillet, H.prism, H.box, H.cut, H.lathe
    TOP = .0852; HW = .0136; ZB = .0494

    def fin(ob, w=H.BW_FINE, seg=1):
        # 單段導角配 Weighted Normal：一道斜面就有圓角的高光，面數只有三段的三分之一
        H.bevel_now(ob, w, seg=seg, angle=math.radians(44) if ob.get('prebevel') else H.BEV_ANGLE); return ob

    # ---- 滑套：圓肩矩形斷面，前端下緣斜切 ----
    sec = F([(-HW, ZB, .0006), (HW, ZB, .0006), (HW, TOP - .0052, .0052), (HW - .0034, TOP, .0030), (-HW + .0034, TOP, .0030), (-HW, TOP - .0052, .0052)], seg=3)
    sl = P(sec, S0, S1, 'xz', 'slide')
    C(sl, B(-.0108, .0108, S0 - .01, S1 + .01, .03, ZB + .0016))                                  # 滑軌溝
    C(sl, H.rot(B(-.03, .03, S1 - .04, S1 + .03, .03, .0540), (1, 0, 0), 24, (0, S1 - .0040, .0540)),   # 前端下緣斜切
      H.rot(B(-.03, .03, S0 - .03, S0 + .018, TOP - .0030, .11), (1, 0, 0), 15, (0, S0 + .0120, TOP)),
      H.rot(B(-.03, .03, S1 - .03, S1 + .03, TOP, .12), (1, 0, 0), -9, (0, S1 - .0100, TOP)))  # 尾端頂部、前端頂面斜切
    H.bevel_now(sl, H.BW_MID, seg=2)
    cuts = []
    # 勺形刻槽：圓柱沿 Z 掏側面，前七後五，不走斜線，和 P9 的斜刻痕分開
    for sx in (1, -1):
        for i in range(7):
            y = S0 + .0085 + i * .0040
            cuts.append(H.cyl((sx * (HW + .0009), y), .0017, ZB + .0030, TOP - .0044, 'z', 10))
        for i in range(4):
            y = .0660 + i * .0040
            cuts.append(H.cyl((sx * (HW + .0009), y), .0017, ZB + .0034, TOP - .0064, 'z', 10))
    # 頂部減重窗（第一人稱正好看到）：長圓孔，前後各一道斜壁
    cuts.append(P(H.rrect(.0104, .0250, .0034, 4, 0, .0730), TOP - .0034, TOP + .01, 'xy'))
    # 拋殼窗：右側包到頂面
    cuts.append(B(-.0054, .03, .0120, .0500, .0640, .10))
    # 槍口孔、復進桿孔
    cuts.append(H.cyl((0, BZ), .0074, S1 - .02, S1 + .02, n=24))
    # 後照門、準星燕尾
    cuts.append(B(-.012, .012, S0 + .0130, S0 + .0230, TOP - .0014, .10))
    cuts.append(B(-.006, .006, .0900, .0985, TOP - .0012, .10))
    # 尾端蓋板凹座
    cuts.append(P(H.rrect(.0150, .0240, .0020, 3, 0, .0645), S0 - .01, S0 + .0012, 'xz'))
    C(sl, *cuts)
    g.add(fin(sl, .0004), 'oxide', None, group='slide')
    # 尾端蓋板：第一人稱看得到的鋼片，中間撞針孔
    plate = P(H.rrect(.0145, .0235, .0018, 3, 0, .0645), S0 + .0002, S0 + .0080, 'xz', 'plate')
    C(plate, H.cyl((0, BZ), .0020, S0 - .01, S0 + .01, n=12))
    g.add(fin(plate, .0003), 'steel', None, group='slide')
    g.add(L([(S0 + .0006, .0017), (S0 + .0010, .0017), (S0 + .0010, 0)], 10, (0, BZ)), 'alum', None, group='slide')
    # 拉殼鉤：右側嵌片 + 銷
    g.add(fin(P(F([(.0505, .0668, .0006), (.0660, .0668, .0006), (.0660, .0710, .0012), (.0505, .0718, .0006)], seg=2), HW - .0050, HW + .0005, 'yz', 'ext'), .0002), 'steel', None, group='slide')
    g.pin(HW + .0004, .0620, .0690, r=.0011, h=.0004, dome=False, group='slide')
    # 槍管：方形膛室蓋＋前段圓管
    hood = P(F([(-.0079, .0595, .0006), (.0079, .0595, .0006), (.0079, .0835, .0010), (-.0079, .0835, .0010)], seg=2), .0100, .0505, 'xz', 'hood')
    C(hood, B(-.0024, .0024, .0050, .0190, .0800, .09))
    g.add(fin(hood, .0004), 'steel', None)
    # 上膛指示片：後緣翹起的小鋼片
    g.add(fin(P(F([(.0110, .0820, .0003), (.0178, .0820, .0003), (.0178, .0830, .0003), (.0110, .0846, .0004)], seg=1), -.0022, .0022, 'yz', 'lci'), .0002), 'alum', None)
    g.add(L([(.0500, .0072), (S1 - .0012, .0072), (S1 - .0004, .0066), (S1 - .0002, .0040), (S1 - .0120, .0034), (S1 - .0120, 0)], 22, (0, BZ)), 'steel', None)
    # 復進桿頭
    g.add(L([(.0900, .0048), (S1 - .0026, .0048), (S1 - .0024, .0020), (S1 - .0050, .0020), (S1 - .0050, 0)], 16, (0, .0520)), 'oxide', None)
    # 槍口前臉
    g.add(L([(S1 - .0004, .0074), (S1 + .0008, .0074), (S1 + .0014, .0058), (S1 + .0014, .0044), (S1 + .0002, .0038), (S1 + .0002, 0)], 22, (0, BZ)), 'steel', None)

    # ---- 準星與後照門 ----
    fs = P(F([(.0905, TOP - .0014, .0003), (.0980, TOP - .0014, .0003), (.0975, TOP + .0010, .0003), (.0945, TOP + .0048, .0005), (.0920, TOP + .0048, .0005)], seg=2), -.0017, .0017, 'yz', 'fs')
    g.add(fin(fs, .0002), 'oxide', None, group='slide')
    g.add(P(F([(.0905, TOP - .0014, .0), (.0985, TOP - .0014, .0), (.0985, TOP - .0002, .0), (.0905, TOP - .0002, .0)], seg=1), -.0052, .0052, 'yz', 'fsb'), 'oxide', None, group='slide')
    g.add(L([(.0916, .0010), (.0921, .0010), (.0921, 0)], 10, (0, TOP + .0030)), 'dot', None, group='slide')
    rs = P(F([(-.0092, 0, .0004), (.0092, 0, .0004), (.0092, .0058, .0010), (.0070, .0068, .0004), (.0021, .0068, .0), (.0021, .0030, .0003), (-.0021, .0030, .0003), (-.0021, .0068, .0), (-.0070, .0068, .0004), (-.0092, .0058, .0010)], seg=2), S0 + .0134, S0 + .0226, 'xz', 'rs')
    H.move(rs, 0, 0, TOP - .0014)
    C(rs, H.rot(B(-.02, .02, S0 + .0215, S0 + .05, TOP - .01, TOP + .02), (1, 0, 0), 28, (0, S0 + .0215, TOP + .0015)))   # 前斜面，防勾掛
    g.add(fin(rs, .0003), 'oxide', None, group='slide')
    for sx in (1, -1):
        g.add(L([(S0 + .0130, .0009), (S0 + .0136, .0009), (S0 + .0136, 0)], 10, (sx * .0058, TOP + .0034)), 'dot', None, group='slide')

    # ---- 滑軌：滑套下窄縫 ----
    g.add(B(-.0106, .0106, S0 + .0020, .0950, .0460, ZB + .0014), 'oxide', None)

    # ---- 槍身：聚合物，尾端虎口護片一體成形 ----
    prof = F([(S0 + .0010, .0466, .001), (.0985, .0466, .001), (.0985, .0322, .003), (.0900, .0306, .002), (.0800, .0262, .004), (.0280, .0250, .004), (.0150, .0215, .004),
              (-.0130, .0215, .005), (-.0205, .0255, .004), (S0 + .0130, .0300, .006), (S0 - .0025, .0345, .006), (S0 - .0040, .0440, .004)], seg=3)
    fr = P(prof, -.0134, .0134, 'yz', 'frame')
    H.bevel_now(fr, H.BW_MID, seg=2)
    cuts = []
    for sx in (1, -1):
        # 防塵蓋側面長溝、滑套擋榫凹槽
        cuts.append(P(F([(.0660, .0352, .0012), (.0950, .0362, .0012), (.0950, .0412, .0012), (.0660, .0412, .0012)], seg=2), sx * .0125, sx * .03, 'yz'))
        cuts.append(P(F([(.0090, .0345, .0015), (.0500, .0345, .0015), (.0500, .0425, .0015), (.0090, .0425, .0015)], seg=2), sx * .0128, sx * .03, 'yz'))
    # 防塵蓋下的配件槽兩道
    for i in range(2):
        y = .0838 + i * .0078
        cuts.append(B(-.03, .03, y, y + .0040, .02, .0326))
    C(fr, *cuts)
    g.add(fin(fr, .0004), 'poly', None)
    # 拇指檔：握把上緣兩側的短凸脊
    for sx in (1, -1):
        rest = P(F([(-.0230, .0268, .001), (.0100, .0245, .001), (.0100, .0285, .001), (-.0230, .0312, .001)], seg=2), sx * .0132, sx * .0150, 'yz', 'rest')
        g.add(fin(rest, .0003), 'poly', None)

    # ---- 握把：尺寸不動，手臂貼這個面 ----
    def gsec(s):
        rx = .0132 + .0013 * math.sin(s * 3.14)
        return F([(-rx, -.0235 - .0015 * s, .0090), (rx, -.0235 - .0015 * s, .0090), (rx, .0205 + .0015 * s, .0065), (-rx, .0205 + .0015 * s, .0065)], seg=4)
    a = (0, .0100, .0335); b = (0, -.0235, -.0640)
    grip = H.loft_frames(H.grip_stations(a, b, gsec, 6, -.0012), 'grip')
    # 彈匣井：底部開口，彈匣抽走時看得到空腔
    ax = (H.Vector(b) - H.Vector(a)).normalized(); fw = H.Vector((0, 1, 0)); fw = (fw - ax * fw.dot(ax)).normalized()
    def mframe(t, s):
        return (tuple(H.Vector(a) + ax * t), (1, 0, 0), tuple(fw), s)
    well = H.loft_frames([mframe(.070, H.rrect(.0192, .0345, .0030, 2, 0, -.0020)), mframe(.112, H.rrect(.0222, .0380, .0040, 2, 0, -.0020))], 'well')
    C(grip, well)
    g.add(grip, 'grip', None, knurl=dict(a=a, b=b, pitch=.0017, lo=.10, hi=.90))
    # 彈匣井外擴口：握把底緣一圈硬邊，帶出分件縫
    cflare = H.loft_frames([mframe(.0985, H.rrect(.0288, .0490, .0085, 3, 0, -.0022)), mframe(.1040, H.rrect(.0298, .0506, .0088, 3, 0, -.0022))], 'flare')
    C(cflare, H.loft_frames([mframe(.090, H.rrect(.0200, .0360, .0030, 2, 0, -.0020)), mframe(.112, H.rrect(.0226, .0386, .0040, 2, 0, -.0020))], 'wellb'))
    g.add(fin(cflare, .0003), 'poly', None)

    # ---- 扳機護弓與扳機：沿用 P9 尺寸 ----
    outer = F([(.0160, .0330, .002), (.0220, -.0040, .007), (.0720, -.0085, .004), (.0760, -.0060, .002), (.0800, .0030, .003), (.0815, .0330, .002)], seg=3)
    inner = F([(.0240, .0350, .001), (.0285, .0010, .005), (.0690, -.0030, .003), (.0735, .0060, .002), (.0750, .0350, .001)], seg=3)
    tg = P(outer, -.0078, .0078, 'yz', 'tg'); C(tg, P(inner, -.02, .02, 'yz'))
    g.add(fin(tg, .0007), 'poly', None)
    tr = P(F([(.0465, .0340, .0), (.0530, .0340, .0), (.0500, .0180, .004), (.0445, .0065, .002), (.0420, .0070, .001), (.0465, .0180, .005)], seg=3), -.0040, .0040, 'yz', 'trg')
    g.add(fin(tr, .0003), 'oxide', None)
    # 中央保險片貼在扳機前面：手臂解算沿中線量扳機面，不能在中線開溝
    g.add(P(F([(.0500, .0300, .0), (.0534, .0300, .0), (.0512, .0170, .002), (.0466, .0080, .001), (.0452, .0080, .001), (.0490, .0170, .002)], seg=2), -.0008, .0008, 'yz', 'tsf'), 'steel', None)

    # ---- 控制件 ----
    # 滑套擋榫：左側長片＋止滑齒
    stop = P(F([(.0130, .0392, .0008), (.0420, .0392, .0008), (.0440, .0416, .0006), (.0420, .0436, .0008), (.0130, .0436, .0008)], seg=2), -.0142, -.0100, 'yz', 'stop')
    C(stop, *[B(-.02, -.0137, .0150 + i * .0024, .0162 + i * .0024, .035, .05) for i in range(4)])
    g.add(fin(stop, .0002), 'oxide', None)
    g.add(L([(-.0145, .0030), (-.0126, .0030), (-.0126, 0)], 12, (.0395, .0414), 'x'), 'oxide', None)
    # 拆解卡榫（雙側）
    for sx in (1, -1):
        g.add(fin(P(F([(.0590, .0362, .0005), (.0660, .0362, .0005), (.0660, .0420, .0005), (.0590, .0420, .0005)], seg=1), sx * .0090, sx * .0139, 'yz', 'td'), .0002), 'oxide', None)
    # 彈匣釋放鈕：左側
    g.add(fin(B(-.0150, -.0090, .0130, .0240, .0150, .0250), .0003), 'oxide', None)
    # 固定銷
    for sx in (1, -1):
        g.pin(sx * .0134, -.0400, .0400, r=.0020, h=sx * .0005, mat='oxide', dome=False)
        g.pin(sx * .0125, .0600, .0390, r=.0018, h=sx * .0005, mat='oxide', dome=False)
        g.pin(sx * .0134, -.0020, .0310, r=.0016, h=sx * .0004, mat='steel', dome=False)

    # ---- 加長彈匣：鋼匣身整條做出來，換彈時才拔得出一支完整的彈匣 ----
    def msec(s):
        return H.rrect(.0178, .0320, .0030, 2, 0, -.0020)
    M0, M1 = .002, .1120
    mag = H.loft_frames([mframe(M0, msec(0)), mframe(M1, msec(1))], 'mag')
    cuts = []
    for i in range(5):   # 背面計數孔
        t = .040 + i * .0130; c = H.Vector(a) + ax * t
        cuts.append(H.cyl((c[1], c[2]), .0016, .004, .02, 'x', 8))
    C(mag, *cuts)
    g.add(fin(mag, .0005), 'steel', None, group='mag')
    # 彈匣頂唇：第一發彈殼露出，彈匣抽出時才看得到
    lip = H.loft_frames([mframe(M0 - .0040, H.rrect(.0120, .0270, .0020, 2, 0, -.0020)), mframe(M0, H.rrect(.0120, .0270, .0020, 2, 0, -.0020))], 'lip')
    g.add(fin(lip, .0004), 'steel', None, group='mag')
    # 指溝彈匣套：接在握把下方，側面看到加長一截
    def ssec(k, front=0.0):
        # 前緣多一塊就是小指座，只往前長，後緣和握把背線對齊
        w, d = .0282 * k, .0490 * k + front
        return H.rrect(w, d, .0072, 4, 0, -.0022 + front / 2)
    st = H.loft_frames([mframe(.1058, ssec(.97)), mframe(.1075, ssec(1.0)), mframe(.1160, ssec(.985, .0005)), mframe(.1195, ssec(.985, .0040)), mframe(.1245, ssec(.99, .0052)), mframe(.1285, ssec(.99, .0022)), mframe(.1330, ssec(1.0, .0)),
                        mframe(.1345, ssec(1.035, .0005)), mframe(.1395, ssec(1.035, .0005)), mframe(.1412, ssec(.98, .0))], 'sleeve')
    cuts = []
    for i in range(3):   # 側面止滑橫溝
        c = H.Vector(a) + ax * (.1100 + i * .0062)
        for sx in (1, -1):
            cuts.append(H.rot(B(sx * .0132, sx * .02, c[1] - .03, c[1] + .03, c[2] - .0011, c[2] + .0011), (1, 0, 0), math.degrees(math.atan2(fw[2], fw[1])), tuple(c)))
    C(st, *cuts)
    g.add(fin(st, .0003), 'rubber', None, group='mag')
    g.marks['muzzle'] = (0, S1 + .0014, BZ)
    return g
