export function cycleOption(state, id, delta) {
  const o = PHOTO_OPTIONS.find((x) => x.id === id);
  const n = o.values.length;
  state[id] = (((state[id] ?? o.def) + delta) % n + n) % n;
  return o.values[state[id]];
}

export function apertureF(label) {
  const m = /f\/([\d.]+)/.exec(label);
  return m ? Number(m[1]) : 0;
}
