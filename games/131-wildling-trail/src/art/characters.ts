// 地圖角色：16×16，四方向 × 三幀（0 站立、1 / 2 左右腳交替）。
// 頭與身體用字元格手繪（每個角色各自的輪廓），腿與手臂依方向與幀數程式化擺動，
// 最後自動補上一像素的加深色描邊。left 由 right 左右翻轉而來。

import { C } from './palette';
import { Canvas } from './raster';

export type CharDir = 'up' | 'down' | 'left' | 'right';

interface CharSpec {
  /** 字元 → 色盤索引（會與共用 legend 合併）。 */
  legend: Record<string, number>;
  down: string;
  up: string;
  right: string;
  /** 手臂：袖子顏色、手的顏色、起始列、袖長、正面時左右手的 x。 */
  arm: { sleeve: number; sleeveShade: number; hand: number; y: number; len: number; x: [number, number]; big?: boolean };
  /** 腿：由上到下每一列的顏色（最後一列是鞋），腿的起始列，正面時左右腿的 x（各 2 像素寬）。 */
  legs: { rows: number[]; shade: number[]; y: number; x: [number, number] };
}

const BASE: Record<string, number> = {
  k: C.skin, K: C.skinShade, e: C.ink, w: C.paper, W: C.mist, m: C.rose,
};

