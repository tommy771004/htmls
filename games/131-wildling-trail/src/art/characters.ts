export const CHARACTER_IDS = Object.keys(SPECS);

function drawLegsFront(c: Canvas, s: CharSpec, frame: number): void {
  const { rows: cols, shade, y, x } = s.legs;
  const n = cols.length;
  x.forEach((lx, side) => {
    // 幀 1：右腳（side 1）抬起；幀 2：左腳抬起。抬起的腳整條短一格。
    const lifted = (frame === 1 && side === 1) || (frame === 2 && side === 0);
    for (let i = lifted ? 1 : 0; i < n; i++) {
      const row = lifted ? y + i - 1 : y + i;
      c.set(lx, row, cols[i]).set(lx + 1, row, i === n - 1 ? cols[i] : shade[i]);
    }
  });
}

function drawLegsSide(c: Canvas, s: CharSpec, frame: number): void {
  const { rows: cols, shade, y } = s.legs;
  const n = cols.length;
  const leg = (offsets: number[], colors: number[], shoeDx: number) => {
    for (let i = 0; i < n; i++) {
      const lx = 7 + offsets[i];
      if (i === n - 1) {
        c.set(lx, y + i, colors[i]).set(lx + 1, y + i, colors[i]).set(lx + shoeDx, y + i, colors[i]);
      } else c.set(lx, y + i, colors[i]).set(lx + 1, y + i, colors[i]);
    }
  };
  const spread = (sign: number) => Array.from({ length: n }, (_, i) => Math.round((sign * i * 2) / (n - 1)));
  if (frame === 0) {
    leg(new Array(n).fill(0), cols, 2);
    return;
  }
  // 幀 1：近側腳在前；幀 2：近側腳在後。遠側腳用暗色。
  const nearFwd = frame === 1;
  leg(spread(nearFwd ? -1 : 1), shade, 2);
  leg(spread(nearFwd ? 1 : -1), cols, 2);
}

function drawArmsFront(c: Canvas, s: CharSpec, frame: number): void {
  const a = s.arm;
  a.x.forEach((ax, side) => {
    // 抬起的腳對側的手往前擺（手低一格），同側的手往後（手高一格）
    let dy = 0;
    if (frame === 1) dy = side === 0 ? 1 : -1;
    if (frame === 2) dy = side === 1 ? 1 : -1;
    const len = Math.max(1, a.len + dy);
    for (let i = 0; i < len; i++) c.set(ax, a.y + i, i === len - 1 && len > 1 ? a.sleeveShade : a.sleeve);
    const hy = a.y + len;
    c.set(ax, hy, a.hand);
    if (a.big) c.set(side === 0 ? ax - 1 : ax + 1, hy, a.hand).set(ax, hy + 1, a.hand).set(side === 0 ? ax - 1 : ax + 1, hy - 1, a.hand);
  });
}

function drawArmSide(c: Canvas, s: CharSpec, frame: number): void {
  const a = s.arm;
  const x0 = 7;
  // 幀 0：垂在身側；幀 1：往後擺；幀 2：往前擺
  const dx = frame === 0 ? 0 : frame === 1 ? -1 : 1;
  for (let i = 0; i < a.len; i++) c.set(x0 + (i === a.len - 1 ? dx : 0), a.y + i, i === 0 ? a.sleeve : a.sleeveShade);
  const hx = x0 + dx * 2, hy = a.y + a.len - (frame === 0 ? 0 : 0);
  c.set(hx, hy, a.hand);
  if (a.big) c.set(hx + (dx || 1), hy, a.hand).set(hx, hy + 1, a.hand).set(hx + (dx || 1), hy + 1, a.hand);
}

export function drawCharacter(id: string, dir: CharDir, frame: number): Canvas {
  const s = SPECS[id];
  if (!s) throw new Error(`no art for character ${id}`);
  if (dir === 'left') return drawCharacter(id, 'right', frame).flipX();
  const c = new Canvas(16, 16);
  const legend = { ...BASE, ...s.legend };
  if (dir === 'right') {
    drawLegsSide(c, s, frame);
    c.stamp(0, 0, rows(s.right), legend);
    drawArmSide(c, s, frame);
  } else {
    drawLegsFront(c, s, frame);
    c.stamp(0, 0, rows(dir === 'down' ? s.down : s.up), legend);
    drawArmsFront(c, s, frame);
  }
  return c.outline();
}
